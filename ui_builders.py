        p0_out_min_hz, p0_out_max_hz = _effective_limits(win.config.device_limits.p0_freq_min, win.config.device_limits.p0_freq_max, 1.0, 100.0)
        c0_out_min_hz, c0_out_max_hz = _effective_limits(win.config.device_limits.c0_freq_min, win.config.device_limits.c0_freq_max, 500.0, 1500.0)
        p1_out_min, p1_out_max = _effective_limits(win.config.device_limits.p1_cycles_min, win.config.device_limits.p1_cycles_max, 0.0, 20.0)
