    win.metric_status_label.setStyleSheet("color: #AAA; font-size: 9px;")
    status_row.addWidget(win.metric_status_label)
    status_row.addStretch()
    metric_layout.addLayout(status_row)
    
    # Enable metrics based on config (first load = True, then saved)
    global_on = win.config.auto_adjust.metrics_global_enabled
    win.metric_audio_amp_cb.setChecked(global_on)
    if global_on:
        print("[Config] Auto-enabled Audio Amp metric from config")

    # ===== LEVELS: Audio Amplification, Sensitivity, Flux Multiplier =====
    levels_layout = auto_levels_layout
    
    # Frequency band selection with visibility toggle (red beat detection band)
    beat_slider_row = QHBoxLayout()
    win.freq_range_slider = RangeSliderWithLabel("Freq Range (Hz)", 30, 22050, 100, 8000, 0, log_scale=True)
