        p0_sent_max = max(float(win.p0_sent_min_spin.value()), float(win.p0_sent_max_spin.value()))
        win.config.pulse_freq.tcode_min = _unit_to_tcode(p0_sent_min, p0_out_min_hz, p0_out_max_hz)
        win.config.pulse_freq.tcode_max = _unit_to_tcode(p0_sent_max, p0_out_min_hz, p0_out_max_hz)

        f0_sent_min = min(float(win.f0_sent_min_spin.value()), float(win.f0_sent_max_spin.value()))
        f0_sent_max = max(float(win.f0_sent_min_spin.value()), float(win.f0_sent_max_spin.value()))
        win.config.carrier_freq.tcode_min = _unit_to_tcode(f0_sent_min, c0_out_min_hz, c0_out_max_hz)
        win.config.carrier_freq.tcode_max = _unit_to_tcode(f0_sent_max, c0_out_min_hz, c0_out_max_hz)

        p1_sent_min = min(float(win.p1_sent_min_spin.value()), float(win.p1_sent_max_spin.value()))
        p1_sent_max = max(float(win.p1_sent_min_spin.value()), float(win.p1_sent_max_spin.value()))
        win.config.pulse_width.tcode_min = _unit_to_tcode(p1_sent_min, p1_out_min, p1_out_max)
        win.config.pulse_width.tcode_max = _unit_to_tcode(p1_sent_max, p1_out_min, p1_out_max)

        p3_sent_min = min(float(win.p3_sent_min_spin.value()), float(win.p3_sent_max_spin.value()))
        p3_sent_max = max(float(win.p3_sent_min_spin.value()), float(win.p3_sent_max_spin.value()))
