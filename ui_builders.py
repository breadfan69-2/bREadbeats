    win.zscore_threshold_slider.valueChanged.connect(win._on_zscore_threshold_change)
    levels_layout.addWidget(win.zscore_threshold_slider)
    
    # Flux Multiplier
    fm_min, fm_max = BEAT_RANGE_LIMITS['flux_mult']
    win.flux_mult_slider = SliderWithLabel("Flux Multiplier", fm_min, fm_max, win.config.beat.flux_multiplier, 2)
    win.flux_mult_slider.valueChanged.connect(lambda v: setattr(win.config.beat, 'flux_multiplier', v))
    levels_layout.addWidget(win.flux_mult_slider)
    

    # ===== DEPTH/PEAKS: Depth, Peak Decay, Rise Sensitivity =====
    peaks_layout = auto_levels_layout
    
    # Peak floor: minimum energy to consider (0 = disabled)
    # Range 0.01-0.15: typical band_energy is 0.08-0.15 with default gain
    pf_min, pf_max = BEAT_RANGE_LIMITS['peak_floor']
    win.peak_floor_slider = SliderWithLabel("Depth", pf_min, pf_max, win.config.beat.peak_floor, 3)
    win.peak_floor_slider.valueChanged.connect(lambda v: setattr(win.config.beat, 'peak_floor', v))
    peaks_layout.addWidget(win.peak_floor_slider)
    
    # Peak decay
    pd_min, pd_max = BEAT_RANGE_LIMITS['peak_decay']
    win.peak_decay_slider = SliderWithLabel("Peak Decay", pd_min, pd_max, win.config.beat.peak_decay, 3)
    win.peak_decay_slider.valueChanged.connect(lambda v: setattr(win.config.beat, 'peak_decay', v))
    peaks_layout.addWidget(win.peak_decay_slider)
    
    # Rise sensitivity: 0 = disabled, higher = require more rise
    rs_min, rs_max = BEAT_RANGE_LIMITS['rise_sens']
    win.rise_sens_slider = SliderWithLabel("Rise Sensitivity", rs_min, rs_max, win.config.beat.rise_sensitivity)
    win.rise_sens_slider.valueChanged.connect(lambda v: setattr(win.config.beat, 'rise_sensitivity', v))
    peaks_layout.addWidget(win.rise_sens_slider)
    
    layout.addWidget(auto_levels_group)
    
    layout.addStretch()
    scroll_area.setWidget(widget)
    return scroll_area


