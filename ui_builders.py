def create_tempo_tracking_tab(win, include_advanced_controls: bool = False, advanced_locked: bool = True) -> QWidget:
    """Tempo tracking and rhythm settings"""
    scroll_area = NoWheelScrollArea()
    scroll_area.setWidgetResizable(True)
    scroll_area.setHorizontalScrollBarPolicy(Qt.ScrollBarPolicy.ScrollBarAlwaysOff)
    scroll_area.setVerticalScrollBarPolicy(Qt.ScrollBarPolicy.ScrollBarAlwaysOn)

    widget = QWidget()
    layout = QVBoxLayout(widget)

    # ===== TEMPO SETTINGS =====
    tempo_group = CollapsibleGroupBox("Tempo Settings", collapsed=False)
    tempo_layout = QVBoxLayout(tempo_group)
    
    # Enable/disable checkbox
    win.tempo_tracking_checkbox = QCheckBox("Enable Tempo Tracking")
    win.tempo_tracking_checkbox.setChecked(True)
    win.tempo_tracking_checkbox.stateChanged.connect(win._on_tempo_tracking_toggle)
    tempo_layout.addWidget(win.tempo_tracking_checkbox)

    win.tempo_settings_lock_cb = QCheckBox("Lock tempo settings")
    win.tempo_settings_lock_cb.setChecked(False)
    win.tempo_settings_lock_cb.setToolTip("Lock/unlock tempo tuning controls in this group")
    win.tempo_settings_lock_cb.stateChanged.connect(win._on_tempo_settings_lock_toggle)
    tempo_layout.addWidget(win.tempo_settings_lock_cb)
    
    # Time signature dropdown
    sig_layout = QHBoxLayout()
    sig_layout.addWidget(QLabel("Time Signature:"))
    win.time_sig_combo = QComboBox()
    win.time_sig_combo.addItems(["4/4 (4 beats)", "3/4 (3 beats)", "6/8 (6 beats)"])
    win.time_sig_combo.currentIndexChanged.connect(win._on_time_sig_change)
    sig_layout.addWidget(win.time_sig_combo)
    sig_layout.addStretch()
    tempo_layout.addLayout(sig_layout)
    
    # Stability threshold: lower = stricter (requires more consistent intervals before locking BPM)
    win.stability_threshold_slider = SliderWithLabel("Stability Threshold", 0.05, 0.4, 0.15, 2)
    win.stability_threshold_slider.valueChanged.connect(partial(win._on_tempo_param_change, 'stability_threshold', 'stability_threshold'))
    tempo_layout.addWidget(win.stability_threshold_slider)
    
    # Tempo timeout: how long no beats before resetting tempo tracking
    win.tempo_timeout_slider = SliderWithLabel("Tempo Timeout (ms)", 500, 5000, 2000, 0)
    win.tempo_timeout_slider.valueChanged.connect(partial(win._on_tempo_param_change, 'tempo_timeout_ms', 'tempo_timeout_ms', transform=int))
    tempo_layout.addWidget(win.tempo_timeout_slider)
    
    # Phase snap: how much to nudge detected beats toward predicted time
    win.phase_snap_slider = SliderWithLabel("Phase Snap", 0.0, 0.8, 0.3, 2)
    win.phase_snap_slider.valueChanged.connect(partial(win._on_tempo_param_change, 'phase_snap_weight', 'phase_snap_weight'))
    tempo_layout.addWidget(win.phase_snap_slider)
    
    # Silence reset threshold (moved from Beat Detection)
    win.silence_reset_slider = SliderWithLabel("Silence Reset (ms)", 100, 3000, 180, 0)
    win.silence_reset_slider.valueChanged.connect(lambda v: setattr(win.config.beat, 'silence_reset_ms', int(v)))
    tempo_layout.addWidget(win.silence_reset_slider)

    win._tempo_settings_lock_targets = [
        win.time_sig_combo,
        win.stability_threshold_slider,
        win.tempo_timeout_slider,
        win.phase_snap_slider,
        win.silence_reset_slider,
    ]

    win._apply_tempo_settings_enabled_state(win.tempo_tracking_checkbox.isChecked())
    
    layout.addWidget(tempo_group)

    if include_advanced_controls:
        layout.addWidget(win._create_tempo_response_group(lock_default=advanced_locked))
    
    layout.addStretch()
    scroll_area.setWidget(widget)
    return scroll_area

